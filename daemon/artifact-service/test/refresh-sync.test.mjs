const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SERVICE_DIR = path.resolve(__dirname, "..");
const HMAC_KEY = "dev-insecure-hmac-key-change-me";
const TENANT_ID = "11111111-1111-1111-1111-111111111111";
const API_CLIENT_ID = "22222222-2222-2222-2222-222222222222";
const SPA_CLIENT_ID = "33333333-3333-3333-3333-333333333333";
const ADMIN_OID = "44444444-4444-4444-4444-444444444444";
const USER_OID = "55555555-5555-5555-5555-555555555555";
// Ephemeral test-only key pair avoids committed private-key fixtures and
// exercises the same RS256/JWKS path used in production.
const { privateKey: PRIVATE_KEY, publicKey: PUBLIC_KEY } = crypto.generateKeyPairSync("rsa", {
  modulusLength: 2048,
});
const jwk = PUBLIC_KEY.export({ format: "jwk" });
const KID = "artifact-test-key";

let passed = 0, failed = 0;
const check = (name, cond, detail = "") =>
  cond ? (passed++, console.log(`${name}: PASS`)) : (failed++, console.log(`${name}: FAIL ${detail}`));

function getPort() {
  return new Promise((resolve) => {
    const s = http.createServer();
    s.listen(0, () => { const p = s.address().port; s.close(() => resolve(p)); });
  });
}

function token({ oid = ADMIN_OID, roles = ["Artifact.Admin"], scope = "access_as_user", audience = API_CLIENT_ID } = {}) {
  const now = Math.floor(Date.now() / 1000);
  const header = Buffer.from(JSON.stringify({ alg: "RS256", typ: "JWT", kid: KID })).toString("base64url");
  const claims = Buffer.from(JSON.stringify({
    aud: audience,
    iss: `https://login.microsoftonline.com/${TENANT_ID}/v2.0`,
    tid: TENANT_ID,
    oid,
    azp: SPA_CLIENT_ID,
    scp: scope,
    roles,
    nbf: now - 10,
    exp: now + 3600,
  })).toString("base64url");
  const signingInput = `${header}.${claims}`;
  const signature = crypto.sign("RSA-SHA256", Buffer.from(signingInput), PRIVATE_KEY).toString("base64url");
  return `${signingInput}.${signature}`;
}

const auth = (accessToken, extra = {}) => ({ Authorization: `Bearer ${accessToken}`, ...extra });
const adminToken = token();
const userToken = token({ oid: USER_OID, roles: [] });

// Local OpenID/JWKS server used by artifact-service token verification.
const oidcPort = await getPort();
const oidc = http.createServer((req, res) => {
  if (req.url === "/.well-known/openid-configuration") {
    res.writeHead(200, { "Content-Type": "application/json" });
    res.end(JSON.stringify({ jwks_uri: `http://127.0.0.1:${oidcPort}/keys` }));
    return;
  }
  if (req.url === "/keys") {
    res.writeHead(200, { "Content-Type": "application/json" });
    res.end(JSON.stringify({ keys: [{ ...jwk, kid: KID, alg: "RS256", use: "sig" }] }));
    return;
  }
  res.writeHead(404).end();
});
await new Promise((resolve) => oidc.listen(oidcPort, resolve));

// Stub refresh daemon verifies the HMAC generated by artifact-service.
const posted = [];
const daemonPort = await getPort();
const daemon = http.createServer((req, res) => {
  if (req.method === "POST" && req.url === "/refresh/bootstrap") {
    const chunks = [];
    req.on("data", (c) => chunks.push(c));
    req.on("end", () => {
      const body = Buffer.concat(chunks).toString("utf8");
      const expected = crypto.createHmac("sha256", HMAC_KEY).update(body).digest("hex");
      if (req.headers["x-daemon-sig"] !== expected) {
        res.writeHead(401, { "Content-Type": "application/json" });
        res.end(JSON.stringify({ error: "bad sig" }));
        return;
      }
      const json = JSON.parse(body);
      posted.push(json);
      res.writeHead(200, { "Content-Type": "application/json" });
      res.end(JSON.stringify({ seeded: json.series.reduce((n, s) => n + s.observations.length, 0) }));
    });
    return;
  }
  res.writeHead(404).end();
});
await new Promise((resolve) => daemon.listen(daemonPort, resolve));

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "artifact-svc-test-"));
