fs.mkdirSync(filesDir, { recursive: true });
const dbPath = path.join(tmp, "artifacts.db");
const seriesMapPath = path.join(tmp, "series-map.json");
const refreshDbPath = path.join(tmp, "refresh.db");
const csv = "date,value\n2024-01,10\n2024-02,11\n2024-03-15,12\n";
fs.writeFileSync(seriesMapPath, JSON.stringify({ series: {
  test_series: { header: "date,value", valueRange: [0, 1000], minObs: 2 },
  absent_series: { header: "date,value", valueRange: [0, 1000], minObs: 1 },
} }));
{
  const { DatabaseSync } = await import("node:sqlite");
  const rdb = new DatabaseSync(refreshDbPath);
  rdb.exec("CREATE TABLE indicator_history (series_id TEXT NOT NULL, date TEXT NOT NULL, value REAL, is_preliminary INTEGER, observed_at TEXT, PRIMARY KEY (series_id, date))");
  rdb.prepare("INSERT INTO indicator_history VALUES (?,?,?,?,?)").run("test_series", "2024-01", 10, 0, new Date().toISOString());
  rdb.prepare("INSERT INTO indicator_history VALUES (?,?,?,?,?)").run("test_series", "2024-02", 11, 0, new Date().toISOString());
  rdb.close();
}

const svcPort = await getPort();
const svc = spawn("node", ["dist/server.js"], {
  cwd: SERVICE_DIR,
  env: {
    ...process.env,
    PORT: String(svcPort),
    ARTIFACT_DB_PATH: dbPath,
    ARTIFACT_FILES_DIR: filesDir,
    SERIES_MAP_PATH: seriesMapPath,
    REFRESH_DAEMON_URL: `http://127.0.0.1:${daemonPort}`,
    REFRESH_DB_PATH: refreshDbPath,
    DAEMON_HMAC_KEY: HMAC_KEY,
    ENTRA_TENANT_ID: TENANT_ID,
    ARTIFACT_SERVICE_CLIENT_ID: API_CLIENT_ID,
    ARTIFACT_SERVICE_SCOPE: "access_as_user",
    ARTIFACT_ALLOWED_CLIENT_IDS: SPA_CLIENT_ID,
    ARTIFACT_ADMIN_ROLE: "Artifact.Admin",
    OPENID_CONFIG_URL: `http://127.0.0.1:${oidcPort}/.well-known/openid-configuration`,
  },
  stdio: "pipe",
});
svc.on("exit", (code) => { if (code && code !== 0) console.error(`[svc] exited ${code}`); });
for (let i = 0; i < 50; i++) {
  try {
    const health = await fetch(`http://127.0.0.1:${svcPort}/health`).then((r) => r.json());
    if (health.dbReady) break;
  } catch { /* retry */ }
  if (i === 49) throw new Error("artifact-service never became ready");
  await new Promise((resolve) => setTimeout(resolve, 200));
}

// No token, forged legacy headers, wrong scope, and wrong audience all fail.
check("missing token → 401", (await fetch(`http://127.0.0.1:${svcPort}/artifacts`)).status === 401);
check("forged legacy headers → 401", (await fetch(`http://127.0.0.1:${svcPort}/artifacts`, {
  headers: { "X-User-Id": "admin", "X-User-Role": "admin" },
})).status === 401);
check("wrong scope → 401", (await fetch(`http://127.0.0.1:${svcPort}/artifacts`, {
  headers: auth(token({ scope: "wrong" })),
})).status === 401);
check("wrong audience → 401", (await fetch(`http://127.0.0.1:${svcPort}/artifacts`, {
  headers: auth(token({ audience: "wrong" })),
})).status === 401);

